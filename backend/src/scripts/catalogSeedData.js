export function buildSeedCatalog() {
  const categories = CATEGORY_BLUEPRINTS.map(({ code, products, ...category }) => category);
  const products = CATEGORY_BLUEPRINTS.flatMap((category) =>
    category.products.map((variant, index) => {
      const slug = slugify(variant.name);
      const tagSuffix = codeFromText(variant.name);
      const skuSuffix = codeFromText(variant.color || variant.name);

      return {
        name: variant.name,
        slug,
        tagId: `${category.code}-${String(index + 1).padStart(3, "0")}-${tagSuffix}`,
        description: `${variant.detail} for ${variant.occasion}.`,
        price: variant.price,
        categorySlug: category.slug,
        images: [placeholder(variant.imageLabel || variant.name)],
        stock: variant.stock,
        color: variant.color,
        material: variant.material,
        size: variant.size ?? "5.5m",
        sku: `${category.code}-${String(index + 1).padStart(3, "0")}-${skuSuffix}`,
        isActive: true,
      };
    })
  );

  return { categories, products };
}
