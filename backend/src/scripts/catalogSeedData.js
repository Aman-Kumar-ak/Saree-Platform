import { slugify } from "../lib/slugify.js";

function placeholder(label) {
  return `https://placehold.co/480x720/f8f4ee/5b4330/png?text=${encodeURIComponent(label)}`;
}

function codeFromText(value) {
  const parts = slugify(value)
    .split("-")
    .filter(Boolean);
  if (!parts.length) return "VAR";
  return parts
    .map((part) => part[0])
    .join("")
    .toUpperCase()
    .slice(0, 3)
    .padEnd(3, "X");
}

